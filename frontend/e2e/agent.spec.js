import { test, expect } from '@playwright/test'

test('Agent：编辑、确认、刷新恢复、拒绝以及公开回复', async ({ page, request }) => {
  test.skip(process.env.E2E_AGENT !== '1', '使用隔离的Agent模型替身服务')
  const base = 'http://127.0.0.1:8011/api/v1', password = process.env.E2E_PASSWORD || 'BrowserTest123'
  const email = `agent-${Date.now()}@example.com`
  await request.post(`${base}/auth/register`, { data: { username: '任务测试', email, password, confirm_password: password } })
  const login = async email => ({ Authorization: `Bearer ${(await (await request.post(`${base}/auth/login`, { data: { email, password } })).json()).data.access_token}` })
  const owner = await login(email), agent = await login('browser-agent@example.com')
  const ticket = (await (await request.post(`${base}/tickets`, { headers: owner, data: { title: '登录失败', description: '登录提示账号或密码错误' } })).json()).data
  expect((await request.post(`${base}/tickets/${ticket.id}/claim`, { headers: agent })).status()).toBe(200)
  await page.goto('/login')
  await page.getByLabel('邮箱', { exact: true }).fill('browser-agent@example.com')
  await page.getByLabel('密码', { exact: true }).fill(password)
  await page.getByRole('button', { name: '登录', exact: true }).click()
  await expect(page).toHaveURL(/dashboard/)
  await page.goto(`/agent/tickets/${ticket.id}`)
  const panel = page.getByRole('region', { name: '客服任务助手' })
  await panel.getByRole('button', { name: '新建并运行任务' }).click()
  await expect(panel.getByRole('heading', { name: '等待客服确认' })).toBeVisible()
  expect((await (await request.get(`${base}/tickets/${ticket.id}/notes`, { headers: agent })).json()).data).toHaveLength(0)
  await page.reload()
  await expect(panel.getByRole('heading', { name: '等待客服确认' })).toBeVisible()
  await panel.getByRole('textbox', { name: '待确认内容' }).fill('已核实：请下一位客服继续检查邮箱输入。')
  await expect(panel.getByRole('button', { name: '确认保存内部备注' })).toBeDisabled()
  await panel.getByRole('button', { name: '保存修改' }).click()
  await expect(panel).toContainText('提案版本 2')
  await panel.getByRole('button', { name: '确认保存内部备注' }).click()
  await expect(page.locator('.el-message-box')).toContainText('已核实：请下一位客服继续检查邮箱输入。')
  await page.locator('.el-message-box').getByRole('button', { name: '确认', exact: true }).click()
  await expect(panel).toContainText('内部备注已保存')
  await expect(page.getByRole('region', { name: '内部备注' })).toContainText('已核实：请下一位客服继续检查邮箱输入。')
  expect((await (await request.get(`${base}/tickets/${ticket.id}/comments`, { headers: owner })).json()).data).toHaveLength(0)
  await panel.getByRole('button', { name: '新建并运行任务' }).click()
  await expect(panel.getByRole('heading', { name: '等待客服确认' })).toBeVisible()
  await panel.getByRole('button', { name: '拒绝提案' }).click()
  await expect(panel.getByRole('heading', { name: '已拒绝' })).toBeVisible()
  await panel.getByText('整理内部交接摘要', { exact: true }).click()
  await page.getByRole('option', { name: '拟公开回复' }).click()
  await panel.getByRole('textbox', { name: '任务要求' }).fill('查阅公开知识，为用户拟一份登录排查回复。')
  await panel.getByRole('button', { name: '新建并运行任务' }).click()
  await expect(panel.getByRole('heading', { name: '等待客服确认' })).toBeVisible()
  await expect(panel).toContainText('检索公开知识')
  await panel.getByRole('button', { name: '确认公开发送' }).click()
  await page.locator('.el-message-box').getByRole('button', { name: '确认', exact: true }).click()
  await expect(panel).toContainText('公开回复已发送')
  await page.reload()
  await expect(panel).toContainText('公开回复已发送')
  expect((await (await request.get(`${base}/tickets/${ticket.id}/comments`, { headers: owner })).json()).data).toHaveLength(1)
  await page.screenshot({ path: 'test-results/agent-complete.png', fullPage: true })
  await panel.getByRole('textbox', { name: '任务要求' }).fill('browser-wait：整理摘要，测试取消在途运行')
  await panel.getByRole('button', { name: '新建并运行任务' }).click()
  await panel.getByRole('button', { name: '取消任务' }).click()
  await expect(panel.getByRole('heading', { name: '已取消' })).toBeVisible()
  await expect(panel.getByRole('button', { name: '新建并运行任务' })).toBeEnabled()
  expect((await (await request.get(`${base}/tickets/${ticket.id}/comments`, { headers: owner })).json()).data).toHaveLength(1)
})
